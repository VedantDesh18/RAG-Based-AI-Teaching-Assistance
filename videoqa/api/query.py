router = APIRouter(prefix="/api", tags=["query"])


class QueryRequest(BaseModel):
    # `query` is retained for compatibility with the original client. `question`
    # is the documented public contract.
    query: str | None = None
    question: str | None = None
    video_id: str | None = None
    session_id: str | None = None
    top_k: int | None = Field(default=None, ge=1, le=10)
    scope: str = "single_video"

    @model_validator(mode="after")
    def has_question(self):
        if not (self.question or self.query or "").strip():
            raise ValueError("A question is required")
        return self

    @property
    def text(self) -> str:
        return (self.question or self.query or "").strip()


class ChatRequest(BaseModel):
    session_id: str
    message: str


def seconds_display(seconds: float | int | None) -> str:
    total = max(0, int(seconds or 0))
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    return f"{hours:02d}:{minutes:02d}:{secs:02d}" if hours else f"{minutes:02d}:{secs:02d}"


def event(name: str, payload: dict) -> str:
    return f"event: {name}\ndata: {json.dumps(payload, ensure_ascii=False)}\n\n"


def normalise_citation(chunk: dict) -> dict:
    video_id = chunk.get('video_id')
    start_seconds = float(chunk.get('start_seconds', 0))
    end_seconds = float(chunk.get('end_seconds', start_seconds))
    video = get_video(video_id) if video_id else None
    deeplink = None
    if video and video.get('source_type') == 'youtube':
        # Created from trusted database data, never generated by the model.
        deeplink = f"https://youtu.be/{video_id}?t={int(start_seconds)}"
    return {
        'chunk_id': chunk.get('chunk_id'),
        'video_id': video_id,
        'title': chunk.get('title') or (video or {}).get('title'),
        'start_seconds': start_seconds,
        'end_seconds': end_seconds,
        'start_display': seconds_display(start_seconds),
        'end_display': seconds_display(end_seconds),
        'deeplink': deeplink,
        'text_snippet': (chunk.get('text') or '')[:360],
        'similarity': chunk.get('similarity'),
    }


def stream_ollama(prompt: str):
    response = requests.post(
        f"{config['ollama_url']}/api/generate",
        json={"model": config['model_names']['llm'], "prompt": prompt, "stream": True},
        stream=True,
        timeout=(5, 90),
    )
    response.raise_for_status()
    for line in response.iter_lines():
        if not line:
            continue
        data = json.loads(line)
        token = data.get('response', '')
        if token:
            yield token


def run_query(req: QueryRequest):
    question = req.text
    if req.video_id:
        video = get_video(req.video_id)
        if not video:
            raise HTTPException(status_code=404, detail="Video not found")
        if video.get("status") != "ready" or int(video.get("chunk_count") or 0) < 1:
            raise HTTPException(status_code=409, detail="Chat becomes available after transcript chunks are indexed.")

    session_id = req.session_id or f"sess_{uuid.uuid4().hex[:16]}"
    existing_session = get_chat_session(session_id)
    if existing_session and req.video_id and existing_session.get('video_id') not in {None, req.video_id}:
        raise HTTPException(status_code=409, detail="This chat session belongs to another video")

    now = datetime.now(timezone.utc).isoformat()
    if not existing_session:
        upsert_chat_session({'session_id': session_id, 'video_id': req.video_id, 'created_at': now, 'updated_at': now})
    history = get_chat_messages(session_id, limit=6)
    insert_chat_message(session_id, 'user', question, now)

    def event_stream():
        started_at = time.perf_counter()
        answer_parts: list[str] = []
        citations: list[dict] = []
        grounded = False
        answer_source = 'general_model'
        max_similarity = 0.0
        try:
            # Use recent user turns to retain the subject of concise follow-ups.
            earlier_questions = [m['content'] for m in history if m['role'] == 'user'][-3:]
            retrieval_query = question if not earlier_questions else f"{' '.join(earlier_questions)}\nFollow-up: {question}"
            embedding = create_embedding([retrieval_query])[0]
            retrieval_ms = round((time.perf_counter() - started_at) * 1000)
            top_k = req.top_k or config.get('retrieval', {}).get('top_k', 5)
            threshold = config.get('retrieval', {}).get('abstention_threshold', 0.5)
            chunks = search_vectors(embedding, top_k=top_k, video_id=req.video_id)
            max_similarity = float(chunks[0]['similarity']) if chunks else 0.0
            grounded = bool(chunks and max_similarity >= threshold)
            answer_source = 'videos' if grounded else 'general_model'
            yield event('meta', {'grounded': grounded, 'session_id': session_id})

            conversation = '\n'.join(f"{m['role'].title()}: {m['content']}" for m in history[-6:])
            if grounded:
                transcript_context = '\n\n'.join(
                    f"[Source {index + 1}; Video ID: {chunk.get('video_id', '')}; Title: {chunk.get('title') or (video or {}).get('title') or 'Video'}; {seconds_display(chunk['start_seconds'])}–{seconds_display(chunk['end_seconds'])}] {chunk['text']}"
                    for index, chunk in enumerate(chunks)
                )
                prompt = f"""You are VideoQA, a concise teaching assistant. Answer only from the supplied video transcript excerpts. Do not output timestamps, citations, links, source labels, or markdown links; the application renders verified evidence separately. If the excerpts do not support a claim, say that the video does not establish it.\n\nConversation context:\n{conversation or '(none)'}\n\nTranscript excerpts:\n{transcript_context}\n\nCurrent user question: {question}\nAnswer:"""
                citations = [normalise_citation(chunk) for chunk in chunks]
            else:
                prompt = f"""You are VideoQA. The indexed video did not contain enough evidence to answer the current question. Give a concise, helpful general answer if possible, clearly say it is not grounded in the selected video, and never invent a timestamp, citation, or link.\n\nCurrent user question: {question}\nAnswer:"""

            generation_started = time.perf_counter()
            for token in stream_response(prompt):
                answer_parts.append(token)
                yield event('token', {'text': token})
            generation_ms = round((time.perf_counter() - generation_started) * 1000)
            answer = ''.join(answer_parts).strip() or 'No answer was generated.'
            insert_chat_message(session_id, 'assistant', answer, datetime.now(timezone.utc).isoformat(), citations)
            yield event('done', {
                'grounded': grounded,
                'answer_source': answer_source,
                'citations': citations,
                'closest_matches': [] if grounded else [normalise_citation(chunk) for chunk in chunks[:3]],
                'max_similarity_score': max_similarity,
                'timings': {'retrieval_ms': retrieval_ms, 'generation_ms': generation_ms},
                'session_id': session_id,
            })
        except GeminiConfigurationError:
            message = 'Gemini API key is not configured. Please set GEMINI_API_KEY in your .env file.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except GeminiRateLimitError:
            message = 'Gemini API rate limit or quota exceeded. Please wait a moment and try again.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except GeminiTimeoutError:
            message = 'Gemini API request timed out. Please try again.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except GeminiAuthError:
            message = 'Gemini API authentication failed. Please verify your GEMINI_API_KEY.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except (GeminiAPIError, GeminiError):
            message = 'Gemini API error occurred while generating the answer. Please try again.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except requests.RequestException:
            message = 'The local AI service is unavailable. Check your service configuration and try again.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})
        except Exception:
            message = 'Unable to answer this question right now. Please try again.'
            insert_chat_message(session_id, 'assistant', message, datetime.now(timezone.utc).isoformat(), [])
            yield event('error', {'message': message, 'session_id': session_id})

    return StreamingResponse(event_stream(), media_type='text/event-stream', headers={'Cache-Control': 'no-cache', 'X-Accel-Buffering': 'no'})


@router.post('/query')
def query_endpoint(req: QueryRequest):
    return run_query(req)


@router.post('/chat')
def chat_endpoint(req: ChatRequest):
    session = get_chat_session(req.session_id)
    if not session:
        raise HTTPException(status_code=404, detail='Chat session not found')
    return run_query(QueryRequest(question=req.message, video_id=session.get('video_id'), session_id=req.session_id))


@router.get('/chats')
def list_chats():
    chats = list_chat_sessions()
    return {'sessions': chats, 'total': len(chats)}


@router.get('/chats/{session_id}')
def get_chat(session_id: str):
    session = get_chat_session(session_id)
    if not session:
        raise HTTPException(status_code=404, detail='Chat session not found')
    return {'session': session, 'messages': get_chat_messages(session_id)}
